// Run against a disposable Chromium profile launched with --remote-debugging-port=9222.
// This test changes only that browser's save and clock, never production code/timers.
import assert from 'node:assert/strict';
import { browser } from './browser-client.mjs';
const b=await browser(), key='newgaza2d-save-v1';
const state=()=>b.evaluate(`JSON.parse(localStorage.getItem('${key}'))`);
const click=(action,id)=>b.click(`[data-a="${action}"]${id?`[data-id="${id}"]`:''}`);
const advance=async(ms)=>{await b.evaluate(`window.__offset += ${ms}`);await b.wait(900)};
const clock=()=>b.evaluate(`(()=>{window.__offset=0;const native=Date.now.bind(Date);Date.now=()=>native()+window.__offset})()`);
const select=async(id)=>{
  if(await b.evaluate(`!!document.querySelector('[data-a="close-sheet"]')`))await click('close-sheet');
  await click('zin');await click('zout'); // Save the live camera midpoint after focus animation.
  const s=await state(),d=s.districts.find(d=>d.id===s.currentDistrict),p=d.plots[id],c=d.camera;
  const x=720+((p.x-p.y)*64-c.x)*c.zoom;
  const y=450+((p.x+p.y+2)*32-c.y)*c.zoom;
  assert(x>0&&x<1440&&y>0&&y<900,`plot ${id} outside viewport`);
  await b.send('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,x,y});
  await b.send('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,x,y});
  await b.wait(900);
  await b.until(`!!document.querySelector('[data-a="close-sheet"]')`);
};
try {
 await b.send('Page.navigate',{url:'http://localhost:80/'});
 await b.until(`document.querySelector('#boot.done')`);
 await b.evaluate(`localStorage.removeItem('${key}')`);
 await b.send('Page.reload');
 await b.until(`!!document.querySelector('[data-a="enter"]') && document.querySelector('#boot.done')`);
 await clock();
 await click('enter');
 await click('hide-obj');
 await select(0);
 await click('pickb','recycling');
 const front=await b.evaluate(`document.querySelector('.preview-img')?.src || document.querySelector('#sheet img:last-of-type')?.src`);
 await click('rot');
 await click('place');
 assert.equal((await state()).districts[0].plots[0].orientation,1);
 assert.equal((await state()).coins,985000);
 await b.screenshot('/tmp/newgaza-construction.png');
 await advance(121000);
 assert.equal((await state()).districts[0].plots[0].status,'built');
 await click('close-sheet');
 await click('dlg','fleet');
 for(const kind of ['excavator','bulldozer','truck'])await click('buy',kind);
 assert.equal((await state()).units.length,3);
 const unit=(await state()).units[0];
 await click('upg',unit.id);
 assert.equal((await state()).units[0].level,2);
 await click('close-dlg');
 await select(2);await click('clear');
 let s=await state();assert.equal(s.jobs.length,1);
 const j=s.jobs[0];
 await advance(j.arrival-await b.evaluate('Date.now()')+100);
 assert.equal((await state()).districts[0].plots[2].status,'rubble');
 await b.screenshot('/tmp/newgaza-machinery.png');
 await advance(61000);
 assert.equal((await state()).districts[0].plots[2].status,'empty');
 await advance(92000);
 s=await state();assert(s.inventory.value>0);assert.equal(s.jobs.length,0);
 await click('close-sheet');await click('dlg','mats');
 const coins=s.coins,value=s.inventory.value;
 await click('sell');
 assert.equal((await state()).coins,coins+value);
 assert.equal((await state()).inventory.value,0);
 await click('close-dlg');
 await select(2);await click('cat','housing');await click('pickb','medium_house');
 await click('rot');await click('place');
 assert.equal((await state()).districts[0].plots[2].orientation,1);
 await advance(121000);
 assert(await b.evaluate(`document.querySelector('[data-a="collectB"]').disabled`));
 await advance(3600000);
 assert.equal(await b.evaluate(`document.querySelector('[data-a="collectB"]').disabled`),false);
 await click('collectB');
 await click('close-sheet');
 await click('dlg','projects');
 await click('proj','farm');await advance(301000);await click('cproj','farm');
 assert.equal((await state()).districts[0].projects.find(p=>p.id==='farm').status,'complete');
 await click('close-dlg');
 const saved=await state();
 await b.send('Page.reload');await b.until(`document.querySelector('#boot.done')`);
 assert.equal((await state()).coins,saved.coins);
 assert.equal((await state()).districts[0].plots[2].orientation,1);
 await b.screenshot('/tmp/newgaza-built.png');
 // Phone navigation and dialog containment, using the same real saved progress.
 await b.send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await b.wait(800);await click('dlg','fleet');
 const bounds=await b.evaluate(`(()=>{const r=document.querySelector('dialog').getBoundingClientRect();return{x:r.x,y:r.y,right:r.right,bottom:r.bottom,w:innerWidth,h:innerHeight}})()`);
 assert(bounds.x>=0&&bounds.y>=0&&bounds.right<=bounds.w&&bounds.bottom<=bounds.h);
 await b.screenshot('/tmp/newgaza-mobile-fleet.png');
 await click('close-dlg');await click('map');
 await b.screenshot('/tmp/newgaza-mobile-map.png');
 const shape=await b.evaluate(`({w:innerWidth,scroll:document.documentElement.scrollWidth,pins:document.querySelectorAll('.pin').length})`);
 assert.equal(shape.pins,13);assert(shape.scroll<=shape.w);
 assert.equal(b.errors.length,0,JSON.stringify(b.errors));
 console.log('PASS browser: onboarding, front/back build, timers, machinery, clear/sell, income, projects, saved reload, mobile dialogs and map.');
}finally {b.close()}
